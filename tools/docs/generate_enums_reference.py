# generate_enums_reference.py
"""
Generates docs/EnumsReference.md by scanning src/Bindings/**/*EnumBinding.cpp
and resolving underlying integer values from KenshiLib header declarations.

Usage:
    python tools/docs/generate_enums_reference.py
"""

import os
import re
import sys
import pathlib
from importlib import import_module

PROJECT_ROOT = pathlib.Path(__file__).resolve().parents[2]
BINDINGS_DIR = PROJECT_ROOT / "src" / "Bindings"
OUTPUT_MD = PROJECT_ROOT / "docs" / "EnumsReference.md"

sys.path.insert(0, str(PROJECT_ROOT / "tools" / "luals"))
parse_header_enums = import_module("extract_enum_values").parse_header_enums


def resolve_enum_value(cxx_sym, key, header_values):
    """Resolve an enum identifier or scoped symbol to its numeric value."""
    if cxx_sym in header_values:
        return header_values[cxx_sym]

    parts = cxx_sym.split("::")
    for start in range(1, len(parts) - 1):
        candidate = "::".join(parts[start:])
        if candidate in header_values:
            return header_values[candidate]

    if key in header_values:
        return header_values[key]

    try:
        return int(cxx_sym, 0)
    except ValueError:
        pass

    return None


def parse_enum_bindings():
    header_values = parse_header_enums()
    sections = []
    for path in sorted(BINDINGS_DIR.rglob("*EnumBinding.cpp")):
        sections.extend(parse_enum_binding_file(path, header_values))
    return sections


def parse_enum_binding_file(path, header_values):
    content = path.read_text(encoding="utf-8", errors="ignore")
    pattern = r'^\s*//[ \t]*((?:[\w.-]+/)*[\w.-]+\.h)[ \t]*$'
    chunks = re.split(pattern, content, flags=re.MULTILINE)

    sections = []

    i = 1
    while i < len(chunks):
        header_title = chunks[i]
        section_code = chunks[i+1] if i+1 < len(chunks) else ""

        fn_pattern = r'(void\s+(register\w+)\(lua_State\*\s*L\)\s*\{([^}]+)\})'
        fn_matches = re.findall(fn_pattern, section_code)

        enum_tables = []
        for full_fn, fn_name, fn_body in fn_matches:
            globals_set = re.findall(r'lua_setglobal\(\s*L\s*,\s*"([^"]+)"\s*\);', fn_body)
            nested_set = re.findall(r'setNestedClassTable\(\s*L\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\);', fn_body)
            for parent, field in nested_set:
                globals_set.append(f"{parent}.{field}")

            lines_in_body = fn_body.split("\n")
            set_enum_entries = []

            for line in lines_in_body:
                m = re.search(r'setEnum\(\s*L\s*,\s*"([^"]+)"\s*,\s*([^)]+)\);', line)
                if m:
                    key = m.group(1).strip()
                    val = m.group(2).strip()
                    int_val = resolve_enum_value(val, key, header_values)
                    set_enum_entries.append({
                        "key": key,
                        "val": val,
                        "int_val": int_val
                    })

            if not set_enum_entries:
                continue

            enum_tables.append({
                "func_name": fn_name,
                "globals": globals_set,
                "entries": set_enum_entries
            })

        if enum_tables:
            sections.append({
                "header": header_title,
                "enums": enum_tables
            })

        i += 2

    unresolved = [
        f"{e['key']} ({e['val']})"
        for s in sections
        for t in s["enums"]
        for e in t["entries"]
        if e.get("int_val") is None
    ]
    if unresolved:
        raise ValueError(
            f"Failed to resolve {len(unresolved)} enum values from KenshiLib headers: {', '.join(unresolved[:10])}"
        )

    return sections


def generate_markdown(sections):
    md = []
    md.append("# Enums Reference")
    md.append("")
    md.append("> This document is automatically generated by `tools/docs/generate_enums_reference.py` based on `src/Bindings/**/*EnumBinding.cpp`. Do not edit directly.")
    md.append("")
    md.append("## Overview")
    md.append("")
    total_enums = sum(len(s['enums']) for s in sections)
    total_values = sum(len(e['entries']) for s in sections for e in s['enums'])
    md.append(f"KenshiLua exposes **{total_values}** bound enum values across **{total_enums}** enum tables from **{len(sections)}** SDK header files.")
    md.append("")
    md.append("## Lua Usage & Syntax")
    md.append("")
    md.append("Enum constants retain their exact C++ enumerator names and are exposed through global, namespace, or nested class tables (e.g. `CrimeEnum.CRIME_STEALING`, `OIS.KeyCode.KC_ESCAPE`, or `MeshDataLookup.Dir.FRONT`). Each entry maps to its underlying integer value defined in the KenshiLib headers.")
    md.append("")
    md.append("```lua")
    md.append("-- Accessing enum constants directly:")
    md.append("local prone = ProneState.PS_NORMAL")
    md.append("local crime = CrimeEnum.CRIME_STEALING")
    md.append("local dir   = MeshDataLookup.Dir.FRONT")
    md.append("")
    md.append("-- Passing to a method or setting a property:")
    md.append("character.proneState = ProneState.PS_NORMAL")
    md.append("character:setProneState(ProneState.PS_NORMAL)")
    md.append("")
    md.append("-- Enums evaluate to their bound integer values:")
    md.append("assert(ProneState.PS_NORMAL == 0)")
    md.append("assert(AttachSlot.ATTACH_LEFT_ARM == 50)")
    md.append("assert(itemType.LUA_SCRIPT == 322)")
    md.append("```")
    md.append("")
    md.append("### Creating Convenient Local Aliases")
    md.append("")
    md.append("In Lua, you can easily create your own concise aliases at the top of your scripts for readability and convenience:")
    md.append("")
    md.append("```lua")
    md.append("-- Create local aliases for cleaner code:")
    md.append("local Crime = CrimeEnum")
    md.append("local Prone = ProneState")
    md.append("local Dir   = MeshDataLookup.Dir")
    md.append("")
    md.append("if character.crime == Crime.CRIME_STEALING then")
    md.append("    character:setProneState(Prone.PS_NORMAL)")
    md.append("end")
    md.append("```")
    md.append("")
    md.append("## Table of Contents")
    md.append("")
    for sec in sections:
        header_name = sec["header"]
        anchor = header_name.lower().replace(" ", "-").replace("/", "").replace(".", "")
        globals_list = ", ".join([f"`{g}`" for e in sec["enums"] for g in e["globals"]])
        md.append(f"- [{header_name}](#{anchor}) ({globals_list})")

    md.append("")
    md.append("---")
    md.append("")

    for sec in sections:
        header_name = sec["header"]
        anchor = header_name.lower().replace(" ", "-").replace("/", "").replace(".", "")
        md.append(f"## {header_name}")
        md.append("")

        for enum_info in sec["enums"]:
            globals_str = ", ".join([f"`{g}`" for g in enum_info["globals"]]) if enum_info["globals"] else f"`{enum_info['func_name']}`"
            md.append(f"### Table: {globals_str}")
            md.append("")

            def format_lua_syntax(key):
                if enum_info["globals"]:
                    return "<br>".join([f"`{g}.{key}`" for g in enum_info["globals"]])
                return f"`{key}`"

            if enum_info["entries"]:
                md.append("| Lua Syntax | Integer Value | C++ Enumerator |")
                md.append("| :--- | :--- | :--- |")
                for entry in enum_info["entries"]:
                    int_str = str(entry["int_val"]) if entry.get("int_val") is not None else ""
                    if entry["key"] == "LUA_SCRIPT":
                        prefix = enum_info["globals"][0] if enum_info.get("globals") else "itemType"
                        cxx_col = f"`{prefix}::LUA_SCRIPT` *(Added by KenshiLua)*"
                    else:
                        cxx_col = f"`{entry['val']}`"
                    md.append(f"| {format_lua_syntax(entry['key'])} | `{int_str}` | {cxx_col} |")
                md.append("")

        md.append("---")
        md.append("")

    return "\n".join(md)


def main():
    print("Parsing enum binding sources...")
    sections = parse_enum_bindings()
    print(f"Parsed {len(sections)} header sections.")

    markdown_content = generate_markdown(sections)

    OUTPUT_MD.write_text(markdown_content, encoding="utf-8")
    print(f"Successfully generated {OUTPUT_MD}")


if __name__ == "__main__":
    main()
