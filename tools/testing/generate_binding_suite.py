"""Generates tests/in_game/harness/scripts/kltest/suites/binding_inventory.lua
from luals/generated/binding_inventory.json and registered enums.

Verifies the runtime registration of every single class, method, property,
inheritance link, global function, enum table, and constant value.

Usage:
    python tools/testing/generate_binding_suite.py
    python tools/testing/generate_binding_suite.py --check
"""

import argparse
import difflib
import json
import pathlib
import sys

PROJECT_ROOT = pathlib.Path(__file__).resolve().parents[2]
INVENTORY_PATH = PROJECT_ROOT / "luals" / "generated" / "binding_inventory.json"
DEFAULT_OUTPUT_PATH = (
    PROJECT_ROOT
    / "tests"
    / "in_game"
    / "harness"
    / "scripts"
    / "kltest"
    / "suites"
    / "binding_inventory.lua"
)

# Add tools/docs to import path for enum parsing
sys.path.insert(0, str(PROJECT_ROOT / "tools" / "docs"))
import generate_enums_reference  # noqa: E402


def categorize_class(cls):
    src = cls.get("source", "").replace("\\", "/")
    parts = src.split("/")
    if "MyGUI" in parts:
        return "MyGUI"
    if "AI" in parts:
        return "AI"
    if "Animation" in parts:
        return "Animation"
    if "Building" in parts:
        return "Building"
    if "Gui" in parts:
        return "InGameGUI"
    if "Weather" in parts:
        return "Weather"
    if "Util" in parts:
        return "Util"
    if cls.get("kind") == "template_instance":
        return "Containers"
    name = cls["lua_type"]
    if "Character" in name or "Char" in name:
        return "Character"
    if "Combat" in name or "Attack" in name or "Technique" in name:
        return "Combat"
    if "Faction" in name:
        return "Faction"
    if "Item" in name or "Inventory" in name or "Gear" in name:
        return "Items & Inventory"
    if "Town" in name or "Platoon" in name or "Squad" in name:
        return "Town & Platoon"
    if "Zone" in name or "Terrain" in name:
        return "Zone & World"
    if "Dialogue" in name or "Dialog" in name or "Bounty" in name or "Campaign" in name:
        return "Dialogue & Campaign"
    if "Render" in name or "Ogre" in name or "Sound" in name or "King" in name:
        return "Render & Audio"
    return "Core Systems"


def lua_escape_str(s):
    return json.dumps(s)


def generate_lua_code():
    with open(INVENTORY_PATH, "r", encoding="utf-8") as f:
        inv = json.load(f)

    enum_sections = generate_enums_reference.parse_enum_bindings()

    # Extract and sort enums
    enums = []
    seen_enums = set()
    for section in enum_sections:
        for e in section.get("enums", []):
            for g in e.get("globals", []):
                if g in seen_enums:
                    continue
                seen_enums.add(g)
                constants = []
                for entry in e.get("entries", []):
                    int_val = entry.get("int_val")
                    if int_val is not None:
                        # In MSVC, untyped enums containing 32-bit hex values with the MSB set
                        # (e.g. 0xFFFF8000) are treated as signed 32-bit integers, which sign-extend
                        # when cast to lua_Integer (ptrdiff_t).
                        if int_val >= 0x80000000:
                            int_val = int_val - 0x100000000
                        constants.append((entry["key"], int_val))
                if constants:
                    enums.append({"name": g, "constants": constants})

    enums.sort(key=lambda x: x["name"])

    # Categorize classes
    categories = {}
    for c in inv["classes"]:
        cat = categorize_class(c)
        methods = sorted(m["name"] for m in c.get("methods", []))
        getters = []
        setters = []
        for p in c.get("properties", []):
            access = p.get("access", "readwrite")
            if access in ("read", "readonly", "readwrite"):
                getters.append(p["name"])
            if access in ("write", "readwrite"):
                setters.append(p["name"])
        getters.sort()
        setters.sort()

        entry = {
            "name": c["lua_type"],
            "meta": c["metatable"],
            "parent": c.get("parent_metatable", ""),
            "methods": methods,
            "getters": getters,
            "setters": setters,
            "globals": sorted(c.get("global_names", [])),
            "custom_indexer": "TypesBinding.cpp" in c.get("source", ""),
        }
        categories.setdefault(cat, []).append(entry)

    for cat in categories:
        categories[cat].sort(key=lambda x: x["name"])

    global_functions = sorted(gf["name"] for gf in inv.get("global_functions", []))

    lines = []
    lines.append("-- AUTO-GENERATED by tools/testing/generate_binding_suite.py")
    lines.append("-- Do not edit directly; regenerate with python tools/testing/generate_binding_suite.py")
    lines.append("")
    lines.append('local runner = require("kltest.runner")')
    lines.append("")
    lines.append('runner.register_menu_suite("binding-inventory", function(ctx)')
    lines.append("")
    lines.append("    local function resolve_global(path)")
    lines.append("        local cur = _G")
    lines.append('        for part in path:gmatch("[^%.]+") do')
    lines.append('            if type(cur) ~= "table" then return nil end')
    lines.append("            cur = cur[part]")
    lines.append("        end")
    lines.append("        return cur")
    lines.append("    end")
    lines.append("")
    lines.append("    local total_verified_classes = 0")
    lines.append("    local total_verified_methods = 0")
    lines.append("    local total_verified_properties = 0")
    lines.append("")
    lines.append("    local function verify_class_entry(t, entry)")
    lines.append("        local reg = debug.getregistry()")
    lines.append("        local mt = reg[entry.meta]")
    lines.append('        t.assert_not_nil(mt, entry.name .. " metatable missing: " .. entry.meta)')
    lines.append("")
    lines.append("        for i = 1, #entry.methods do")
    lines.append("            local m = entry.methods[i]")
    lines.append("            local fn = mt[m]")
    lines.append('            t.assert_not_nil(fn, entry.name .. "." .. m .. " method missing on " .. entry.meta)')
    lines.append('            t.assert_equal(type(fn), "function", entry.name .. "." .. m .. " must be function")')
    lines.append("            total_verified_methods = total_verified_methods + 1")
    lines.append("        end")
    lines.append("")
    lines.append("        if entry.custom_indexer then")
    lines.append("            -- Value types with custom C closure indexer (e.g. MyGUI.Colour, IntPoint)")
    lines.append("            -- Verify property read and write on a live constructed instance")
    lines.append("            local constructor = mt.new")
    lines.append("            if not constructor and #entry.globals > 0 then")
    lines.append("                local g = resolve_global(entry.globals[1])")
    lines.append("                constructor = g and g.new")
    lines.append("            end")
    lines.append('            t.assert_not_nil(constructor, entry.name .. " has custom indexer but no constructor to verify properties")')
    lines.append("            local inst = constructor()")
    lines.append('            t.assert_not_nil(inst, entry.name .. " constructor returned nil")')
    lines.append("            for i = 1, #entry.getters do")
    lines.append("                local p = entry.getters[i]")
    lines.append('                t.assert_not_nil(inst[p], entry.name .. "." .. p .. " property unreadable on instance")')
    lines.append("                total_verified_properties = total_verified_properties + 1")
    lines.append("            end")
    lines.append("            for i = 1, #entry.setters do")
    lines.append("                local p = entry.setters[i]")
    lines.append("                inst[p] = 0")
    lines.append("            end")
    lines.append("        else")
    lines.append("            local getters = mt.__getters")
    lines.append("            for i = 1, #entry.getters do")
    lines.append("                local p = entry.getters[i]")
    lines.append('                t.assert_not_nil(getters and getters[p], entry.name .. "." .. p .. " getter missing on " .. entry.meta)')
    lines.append("                total_verified_properties = total_verified_properties + 1")
    lines.append("            end")
    lines.append("")
    lines.append("            local setters = mt.__setters")
    lines.append("            for i = 1, #entry.setters do")
    lines.append("                local p = entry.setters[i]")
    lines.append('                t.assert_not_nil(setters and setters[p], entry.name .. "." .. p .. " setter missing on " .. entry.meta)')
    lines.append("            end")
    lines.append("        end")
    lines.append("")
    lines.append('        if entry.parent and entry.parent ~= "" then')
    lines.append("            local parent_mt = reg[entry.parent]")
    lines.append('            t.assert_not_nil(parent_mt, entry.name .. " parent metatable missing: " .. entry.parent)')
    lines.append("            local child_meta = getmetatable(mt)")
    lines.append("            local fallback = child_meta and child_meta.__index")
    lines.append('            t.assert_equal(fallback, parent_mt, entry.name .. " inheritance link broken to " .. entry.parent)')
    lines.append("        end")
    lines.append("")
    lines.append("        for i = 1, #entry.globals do")
    lines.append("            local g = entry.globals[i]")
    lines.append('            t.assert_not_nil(resolve_global(g), entry.name .. " global table missing: " .. g)')
    lines.append("        end")
    lines.append("")
    lines.append("        total_verified_classes = total_verified_classes + 1")
    lines.append("    end")
    lines.append("")

    # Test 1: Global functions
    lines.append('    ctx.test("global functions are registered and callable", function(t)')
    for gf in global_functions:
        lines.append(f'        t.assert_not_nil(_G[{lua_escape_str(gf)}], {lua_escape_str("global function " + gf + " missing")})')
        lines.append(f'        t.assert_equal(type(_G[{lua_escape_str(gf)}]), "function", {lua_escape_str("global " + gf + " must be function")})')
    lines.append("    end)")
    lines.append("")

    # Test 2: Registered enums and constant values
    lines.append('    ctx.test("registered enum tables and constant values", function(t)')
    lines.append("        local total_enums = 0")
    lines.append("        local total_constants = 0")
    lines.append("        local enum_defs = {")
    for enum in enums:
        c_lines = ", ".join(f"{{ {lua_escape_str(k)}, {v} }}" for k, v in enum["constants"])
        lines.append(f"            {{ name = {lua_escape_str(enum['name'])}, constants = {{ {c_lines} }} }},")
    lines.append("        }")
    lines.append("        for i = 1, #enum_defs do")
    lines.append("            local ed = enum_defs[i]")
    lines.append("            local tbl = resolve_global(ed.name)")
    lines.append('            t.assert_not_nil(tbl, "Enum table missing: " .. ed.name)')
    lines.append("            total_enums = total_enums + 1")
    lines.append("            for j = 1, #ed.constants do")
    lines.append("                local c = ed.constants[j]")
    lines.append("                local key, expected_val = c[1], c[2]")
    lines.append('                t.assert_equal(tbl[key], expected_val, ed.name .. "." .. key .. " constant value")')
    lines.append("                total_constants = total_constants + 1")
    lines.append("            end")
    lines.append("        end")
    lines.append(f"        t.assert_equal(total_enums, {len(enums)}, 'verified all registered enum tables')")
    lines.append(f"        t.assert_equal(total_constants, {sum(len(e['constants']) for e in enums)}, 'verified all enum constant values')")
    lines.append("    end)")
    lines.append("")

    # Test 3: Template container factories
    lines.append('    ctx.test("template container instance factories and metatables", function(t)')
    lines.append('        t.assert_not_nil(lektor, "lektor global table missing")')
    lines.append('        local s_lek = lektor.new("string")')
    lines.append('        t.assert_not_nil(s_lek, "lektor.new(\'string\') failed")')
    lines.append('        t.assert_equal(#s_lek, 0, "new string lektor size")')
    lines.append('        local i_lek = lektor.new("int")')
    lines.append('        t.assert_not_nil(i_lek, "lektor.new(\'int\') failed")')
    lines.append('        t.assert_equal(#i_lek, 0, "new int lektor size")')
    lines.append('        local h_lek = lektor.new("hand")')
    lines.append('        t.assert_not_nil(h_lek, "lektor.new(\'hand\') failed")')
    lines.append('        t.assert_equal(#h_lek, 0, "new hand lektor size")')
    lines.append("    end)")
    lines.append("")

    # Categorized class tests
    for cat in sorted(categories.keys()):
        cls_list = categories[cat]
        lines.append(f'    ctx.test("category {cat} class metatables, methods, and properties", function(t)')
        lines.append("        local classes = {")
        for c in cls_list:
            m_list = ", ".join(lua_escape_str(m) for m in c["methods"])
            g_list = ", ".join(lua_escape_str(g) for g in c["getters"])
            s_list = ", ".join(lua_escape_str(s) for s in c["setters"])
            gl_list = ", ".join(lua_escape_str(g) for g in c["globals"])
            parent_lit = lua_escape_str(c["parent"])
            custom_idx_lit = "true" if c["custom_indexer"] else "false"
            lines.append(f"            {{")
            lines.append(f"                name = {lua_escape_str(c['name'])},")
            lines.append(f"                meta = {lua_escape_str(c['meta'])},")
            lines.append(f"                parent = {parent_lit},")
            lines.append(f"                methods = {{ {m_list} }},")
            lines.append(f"                getters = {{ {g_list} }},")
            lines.append(f"                setters = {{ {s_list} }},")
            lines.append(f"                globals = {{ {gl_list} }},")
            lines.append(f"                custom_indexer = {custom_idx_lit},")
            lines.append(f"            }},")
        lines.append("        }")
        lines.append("        for i = 1, #classes do")
        lines.append("            verify_class_entry(t, classes[i])")
        lines.append("        end")
        lines.append("    end)")
        lines.append("")

    # Summary audit test
    total_classes = len(inv["classes"])
    total_methods = sum(len(c.get("methods", [])) for c in inv["classes"])
    total_props = sum(len(c.get("properties", [])) for c in inv["classes"])

    lines.append('    ctx.test("complete binding inventory audit totals match expected count", function(t)')
    lines.append(f"        t.assert_equal(total_verified_classes, {total_classes}, 'total verified classes')")
    lines.append(f"        t.assert_equal(total_verified_methods, {total_methods}, 'total verified methods')")
    lines.append(f"        t.assert_equal(total_verified_properties, {total_props}, 'total verified properties')")
    lines.append("    end)")
    lines.append("end)")
    lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate KenshiLua binding inventory test suite")
    parser.add_argument("--check", action="store_true", help="Verify committed suite without modifying")
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT_PATH, help="Output file path")
    args = parser.parse_args()

    content = generate_lua_code()

    if args.check:
        if not args.output.exists():
            print(f"Error: {args.output} does not exist. Run python tools/testing/generate_binding_suite.py to generate it.")
            sys.exit(1)
        existing = args.output.read_text(encoding="utf-8")
        if existing != content:
            diff = difflib.unified_diff(
                existing.splitlines(keepends=True),
                content.splitlines(keepends=True),
                fromfile=str(args.output),
                tofile="generated",
            )
            print(f"Error: {args.output} is out of date:")
            sys.stdout.writelines(diff)
            sys.exit(1)
        print(f"Check passed: {args.output} is up to date.")
        sys.exit(0)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8", newline="\n")
    print(f"Successfully generated {args.output}")


if __name__ == "__main__":
    main()
